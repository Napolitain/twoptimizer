def chain_page(game, facts="40 wealth from farming (agriculture) (this_building)"):
    extra = "<th>Upkeep Cost</th><th>Food Cost</th>" if game == "three_kingdoms" else ""
    stats = "<td>10</td><td>2</td>" if game == "three_kingdoms" else ""
    if game != "three_kingdoms":
        stats_after = "<td></td><td></td>"
    else:
        stats_after = ""
    return f"""<table><tr><th>No.</th><th>Building</th><th>Create Time</th><th>Create Cost</th>{extra}<th>Effects</th></tr><tr><td>1</td><td><a href="building.php?b=test_1">icon</a></td><td><span>Farm Level 1</span><br><a href="building.php?b=test_1">Test Farm</a><br>description</td></tr><tr><td>3</td><td>1000</td>{stats}<td>{facts}</td>{stats_after}</tr></table>"""


def test_reference_table_keeps_raw_scopes_and_explicit_cost_columns():
    r = parse_chain(chain_page("rome2"), "rome2", "farm")["test_1"]
    assert r["construction_cost"] == 1000
    assert r["upkeep"] is None
    assert r["facts"] == ["40 wealth from farming (agriculture) (this_building)"]
    k = parse_chain(
        chain_page("three_kingdoms", "Building slots: %n (local commandery)"),
        "three_kingdoms",
        "farm",
    )["test_1"]
    assert k["upkeep"] == 10 and k["food_cost"] == 2
    assert "%n" in k["facts"][0]
    with pytest.raises(ValueError):
        number("%n")


def test_source_layout_change_does_not_silently_drop_a_building():
    with pytest.raises(ValueError):
        parse_chain("<table><tr><td>changed</td></tr></table>", "rome2", "farm")
    with pytest.raises(ValueError):
        parse_chain(chain_page("rome2").replace("1000", "unknown"), "rome2", "farm")


def test_shogun_art_effects_and_building_clan_effects_are_retained():
    html = '<div id="page"><h2>Equal Fields</h2><h3>Effects</h3><ul><li>+2% wealth generated by farms across all provinces</li></ul><h3>Clan Effects</h3><ul><li>+1 food</li></ul></div>'
    result = enc_record(
        html,
        "https://liquidwork.github.io/shogun2-encyclopedia/techs/equal_fields.html",
    )
    assert result["facts"] == ["+2% wealth generated by farms across all provinces"]
    assert result["clan_facts"] == ["+1 food"]
    assert (
        next(Document("<script>malicious()</script><p>safe</p>").root.nodes("p")).text()
        == "safe"
    )


def test_shared_rosters_preserve_every_faction_without_merging_identity():
    report = {
        "factions": {
            f: {"id": f, "chains": ["farm"], "buildings": ["farm_1"]}
            for f in ("a", "b")
        }
    }
    share_rosters(report)
    assert len(report["rosters"]) == 1
    assert set(report["factions"]) == {"a", "b"}
    assert report["factions"]["a"]["roster_id"] == report["factions"]["b"]["roster_id"]


@pytest.mark.parametrize("game", ["shogun2", "rome2", "three_kingdoms"])
def test_checked_in_catalog_integrity_and_no_completeness_claim(game):
    catalog = json.loads((DATA / (game + ".json")).read_text())
    report = audit(catalog)
    assert not report["integrity_errors"]
    assert not catalog["ready_for_full_economy_model"]
    assert report["building_records"] > 100
    assert report["source_responses"] > 100
    if game == "three_kingdoms":
        assert report["numeric_placeholder_count"] > 0


def test_export_ingestion_keeps_patch_chunks_duplicate_keys_unicode_and_metadata(
    tmp_path,
):
    source = tmp_path / "source"
    table = source / "db/building_levels_tables"
    table.mkdir(parents=True)
    (table / "base.tsv").write_text(
        "#building_levels;1\nkey\tname\tcost\ncity\t許昌\t100\n", encoding="utf-8-sig"
    )
    (table / "patch.tsv").write_text(
        "key\tname\tcost\n#building_levels;1\ncity\t許昌\t200\n", encoding="utf-16"
    )
    output = tmp_path / "bundle"
    result = ingest(
        source, output, "three_kingdoms", "test-build", mods=["example-mod"]
    )
    assert result["row_count"] == 2 and result["chunk_count"] == 2
    chunks = result["tables"]["building_levels"]["chunks"]
    records = [
        json.loads((output / c["data_file"]).read_text().strip()) for c in chunks
    ]
    assert sorted(int(row[2]) for row in records) == [100, 200]
    assert all(row[:2] == ["city", "許昌"] for row in records)
    assert all(c["columns"] == ["key", "name", "cost"] for c in chunks)
    assert all(c["schema_metadata"] == [["#building_levels;1"]] for c in chunks)
    assert "effects" in result["missing_core_tables"]
    assert not result["ready_for_full_economy_model"]


def test_headerless_exports_are_preserved_instead_of_guessing_columns(tmp_path):
    source = tmp_path / "source"
    source.mkdir()
    (source / "building_levels.tsv").write_text("city_1\t100\ncity_2\t200\n")
    output = tmp_path / "bundle"
    result = ingest(source, output, "shogun2", "test-build")
    chunk = result["tables"]["building_levels"]["chunks"][0]
    assert chunk["columns"] is None and chunk["row_count"] == 2
    assert len((output / chunk["data_file"]).read_text().splitlines()) == 2


def test_incomplete_or_malformed_exports_do_not_publish_a_ready_manifest(tmp_path):
    source = tmp_path / "source"
    source.mkdir()
    (source / "data.pack").write_bytes(b"PFH5")
    with pytest.raises(ValueError, match="Binary"):
        ingest(source, tmp_path / "bundle", "rome2", "build")
    (source / "building_levels.tsv").write_text("key\tcost\ncity_1\t100\textra\n")
    with pytest.raises(ValueError, match="row width"):
        ingest(source, tmp_path / "bundle", "rome2", "build")
    assert not (tmp_path / "bundle/manifest.json").exists()


def test_offline_source_replay_hashes_actual_response_and_never_invents_a_missing_page(
    tmp_path,
):
    from hashlib import sha256

    url = "https://www.honga.net/totalwar/rome2/building.php?l=en&f=rom_rome"
    raw = b"<table><tr><td>reference</td></tr></table>"
    (tmp_path / (sha256(url.encode()).hexdigest() + ".html")).write_bytes(raw)
    sources = Sources(tmp_path, offline=True)
    assert sources.get(url) == raw.decode()
    assert sources.records[url]["sha256"] == sha256(raw).hexdigest()
    with pytest.raises(FileNotFoundError):
        sources.get(url + "&chain=missing")
    with pytest.raises(ValueError):
        sources.get("https://unrecognized.example/data")


def test_core_tables_alone_do_not_claim_a_complete_game_model(tmp_path):
    from games.tw.multigame.import_exports import CORE_TABLES

    source = tmp_path / "source"
    source.mkdir()
    for table in CORE_TABLES:
        (source / (table + ".tsv")).write_text("key\tvalue\nexample\t1\n")
    report = ingest(source, tmp_path / "bundle", "rome2", "build")
    assert not report["missing_core_tables"]
    assert not report["ready_for_full_economy_model"]
    assert report["mods"] is None


def test_export_records_keep_embedded_newlines_and_empty_fields(tmp_path):
    source = tmp_path / "source"
    source.mkdir()
    (source / "effects.tsv").write_text('key\ttext\nrow\t"hello\nworld"\n\t\n')
    output = tmp_path / "bundle"
    report = ingest(source, output, "rome2", "build")
    chunk = report["tables"]["effects"]["chunks"][0]
    rows = [
        json.loads(line)
        for line in (output / chunk["data_file"]).read_text().splitlines()
    ]
    assert rows == [["row", "hello\nworld"], ["", ""]]
