"""Exact recognition of monetary/food/order facts; unsupported facts stay visible."""

import re
from dataclasses import dataclass


@dataclass(frozen=True)
class Effect:
    kind: str
    value: int
    category: str = ""


def parse(text):
    if match := re.fullmatch(r"Cost: ([0-9]+)", text):
        return Effect("construction_cost", int(match[1]))
    if match := re.fullmatch(
        r"([+-][0-9]+) to wealth from (farms|commerce|mines) in this province", text
    ):
        return Effect("wealth", int(match[1]), match[2])
    for pattern, kind in (
        (
            r"([+-][0-9]+)% bonus to (?:clan-wide tax rate|tax rate in this province)",
            "tax_percent",
        ),
        (
            r"([+-][0-9]+)% wealth generated by farms across all provinces",
            "farm_percent",
        ),
        (
            (
                "([+-][0-9]+) per turn to town growth from "
                "(?:commerce|ports|infrastructure) within this province"
            ),
            "building_growth",
        ),
        (
            r"([+-][0-9]+) per turn to economic growth from mastery of the arts",
            "arts_growth",
        ),
        (r"([+-][0-9]+)% to town growth from all buildings", "growth_percent"),
        (
            (
                "([+-][0-9]+) to (?:provincial happiness|repression in this "
                "province|clan-wide happiness|clan-wide repression)"
            ),
            "order",
        ),
        (r"([+-][0-9]+) happiness", "order"),
        (
            r"([+-][0-9]+) happiness for the (?:Buddhist|Christian|Ikko) population",
            "religious_order",
        ),
        (r"([+-][0-9]+)% to trade income \(tariffs only\)", "tariff_percent"),
        (
            r"Increase to trade income \(tariffs only\) by ([+-][0-9]+)%",
            "tariff_percent",
        ),
    ):
        if match := re.fullmatch(pattern, text):
            return Effect(kind, int(match[1]))
    if match := re.fullmatch(r"(Provides|Consumes) food: ([0-9]+)", text):
        return Effect("food", int(match[2]) * (1 if match[1] == "Provides" else -1))
    return None


def family(building):
    key = building["id"]
    if key.startswith("sho_region_specialty_"):
        return "specialty"
    return key.split("_")[1]


def level(building):
    matches = re.findall(r"_([0-9]+)(?:_|$)", building["id"])
    if len(matches) != 1:
        raise ValueError(f"Unrecognized building level: {building['id']}")
    return int(matches[0])


def values(building, kind, category=None):
    return sum(
        e.value
        for text in building["facts"] + building.get("clan_facts", [])
        if (e := parse(text)) and e.kind == kind and (category is None or category == e.category)
    )


def _nanban_reason(nanban_contact, religion, key):
    if not nanban_contact or religion == "ikko":
        return "nanban_contact_or_religion"
    if key.endswith("nanban_quarter") and religion != "christian":
        return "nanban_quarter_requires_christianity"
    return None


def unavailable_reason(building, province, religion, *, nanban_contact=True, clan=None):
    key, group = building["id"], family(building)
    if group == "port" and not province["has_port"]:
        return "no_port_location"
    if group == "specialty":
        prefix = "sho_region_specialty_" + str(province["specialty"]) + "_"
        if province["specialty"] is None or not key.startswith(prefix):
            return "different_province_specialty"
    if group in {"buddhist", "christian", "ikko"} and group != religion:
        return "different_state_religion"
    if group == "christian" and clan is not None and level(building) > 1:
        otomo_branch = any(word in key for word in ("hospital", "jesuit"))
        if otomo_branch != (clan == "otomo"):
            return "different_clan_christian_branch"
    if group == "port" and "nanban" in key:
        return _nanban_reason(nanban_contact, religion, key)
    if group == "portuguese":
        return "one_off_land_sale_not_recurring_tax_wealth"
    return None


def unique_key(building):
    group = family(building)
    if group == "port" and "nanban" in building["id"]:
        return "nanban_chain"
    if building["id"] == "sho_christian_4_jesuit_college":
        return None  # Otomo's regular top-tier branch, not a legendary cathedral.
    if (
        group
        not in {
            "port",
            "castle",
            "farming",
            "infrastructure",
            "specialty",
            "portuguese",
        }
        and level(building) == 4
    ):
        return group
    return None
